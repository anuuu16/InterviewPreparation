// Builds Markdown for the private topics in this folder (personal branch only).
// Usage: node personal/build.js   -> personal/questions/<topic>.md and personal/README.md
const fs = require('fs');
const path = require('path');
const { renderTopic } = require('../app/build');

const DIR = __dirname;
const OUT = path.join(DIR, 'questions');
const topics = fs.readdirSync(DIR).filter((f) => f.endsWith('.json'))
  .map((f) => ({ slug: f.replace(/\.json$/, ''), ...JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8')) }))
  .sort((a, b) => a.name.localeCompare(b.name));

fs.mkdirSync(OUT, { recursive: true });
for (const f of fs.readdirSync(OUT)) if (f.endsWith('.md')) fs.unlinkSync(path.join(OUT, f));
for (const t of topics) {
  const md = renderTopic(t).replace(' · [⭐ Favorites](favorites.md)', '');
  fs.writeFileSync(path.join(OUT, `${t.slug}.md`), md);
}

const n = (t, l) => t.questions.filter((q) => q.level === l).length;
const index = [
  '# Personal topics (private)', '',
  'Generated by `node personal/build.js` from the JSON files in this folder. This folder lives only on the `personal` branch: do not merge it into `main` or push it to a public remote.', '',
  '| Topic | Total | Basic | Intermediate | Advanced |', '| --- | ---: | ---: | ---: | ---: |',
  ...topics.map((t) => `| [${t.name}](questions/${t.slug}.md) | ${t.questions.length} | ${n(t, 'basic')} | ${n(t, 'intermediate')} | ${n(t, 'advanced')} |`), '',
].join('\n');
fs.writeFileSync(path.join(DIR, 'README.md'), index);
console.log(`built ${topics.length} topics`);
